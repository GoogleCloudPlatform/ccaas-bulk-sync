// Precompiles the Vue template in public/index.html (the contents of
// <div id="app">) into a render function, written to public/app-render.js.
// The browser then uses Vue's runtime-only build, which needs no
// 'unsafe-eval' in the Content Security Policy.

const fs = require('fs');
const path = require('path');
const { compile } = require('@vue/compiler-dom');

const PUBLIC_DIR = path.join(__dirname, '..', 'public');
const APP_OPEN_RE = /<div id="app"[^>]*>/;
const APP_END_MARKER = '<script src="/app-render.js"></script>';

/** Returns the inner HTML of <div id="app"> in index.html. */
function extractTemplate(html) {
    const open = APP_OPEN_RE.exec(html);
    if (!open) throw new Error('index.html: <div id="app"> not found');
    const start = open.index + open[0].length;
    const marker = html.indexOf(APP_END_MARKER, start);
    if (marker === -1) throw new Error(`index.html: ${APP_END_MARKER} not found after #app`);
    const end = html.lastIndexOf('</div>', marker);
    if (end < start) throw new Error('index.html: closing </div> for #app not found');
    return html.slice(start, end);
}

/** Compiles a template to browser code that sets window.__ccaasRender. */
function compileTemplate(template) {
    const errors = [];
    const { code } = compile(template, {
        mode: 'function',
        prefixIdentifiers: true, // _ctx.foo instead of with (_ctx) { ... }
        hoistStatic: true,
        cacheHandlers: true,
        onError: (e) => errors.push(e),
        onWarn: (e) => errors.push(e),
    });
    if (errors.length) {
        throw new Error('Template compile errors:\n' + errors.map(e => `- ${e.message}`).join('\n'));
    }
    return '// Generated by scripts/build-ui.js from public/index.html. Do not edit.\n' +
        'window.__ccaasRender = (function (Vue) {\n' + code + '\n})(Vue);\n';
}

function build() {
    const html = fs.readFileSync(path.join(PUBLIC_DIR, 'index.html'), 'utf8');
    const out = compileTemplate(extractTemplate(html));
    fs.writeFileSync(path.join(PUBLIC_DIR, 'app-render.js'), out);
    return out.length;
}

if (require.main === module) {
    const bytes = build();
    console.log(`Wrote public/app-render.js (${bytes} bytes)`);
}

module.exports = { extractTemplate, compileTemplate };
